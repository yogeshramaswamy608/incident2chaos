"""Write the yearly Incident Coverage Report from the released corpus, every figure by script."""

import sys
from collections import Counter

from incident2chaos import __version__
from incident2chaos.codebook import CHAOS_MESH_COMMIT, LITMUS_CHARTS_COMMIT, fault_name, injectability, triggers
from incident2chaos.coverage import measure
from incident2chaos.generate import corpus_rows


def pct(x):
    return f"{100 * x:.1f}"


def main(out):
    rows = corpus_rows()
    overall = measure(rows)[0][0]
    by_source = [r for r in measure(rows, by="source")[0] if r["group"] != "All"]
    by_year = [r for r in measure(rows, by="year")[0] if r["group"] != "All"]
    by_trigger = [r for r in measure(rows, by="trigger")[0] if r["group"] not in ("All", "")]
    names = {k: v["name"] for k, v in triggers().items()}
    scoped = [r for r in rows if r["in_scope"] == "yes" and r["fault_primary"] not in ("", "F99")]
    approx = Counter(r["fault_primary"] for r in scoped if injectability(r["fault_primary"], r["source"]) == "P")
    lines = [
        "# Incident Coverage Report 2026",
        "",
        "How much of what breaks in public cloud incidents can today's open-source chaos tools inject?",
        "",
        f"Yogesh Ramaswamy, Independent Researcher. Generated by incident2chaos {__version__} from its released corpus; "
        f"Chaos Mesh commit {CHAOS_MESH_COMMIT}, LitmusChaos chaos-charts commit {LITMUS_CHARTS_COMMIT}.",
        "",
        "## The answer",
        "",
        f"Of the {overall['stated']} public post-incident reports that state their primary failure, "
        f"{overall['A']} ({pct(overall['A_share'])} percent, 95 percent interval {pct(overall['A_low'])} to "
        f"{pct(overall['A_high'])}) have a primary failure that Chaos Mesh or LitmusChaos can inject directly. "
        f"{overall['P']} can only be approximated and {overall['N']} cannot be injected at all.",
        "",
        "## The failures the tools only approximate",
        "",
        "| Fault class | Reports |",
        "|---|---|",
    ]
    for code, n in approx.most_common():
        lines.append(f"| {code} {fault_name(code)} | {n} |")
    lines += ["", "## By provider", "", "| Provider | Reports | Direct | Approximation | Not injectable | Direct share, % (95% interval) |",
              "|---|---|---|---|---|---|"]
    for r in by_source:
        lines.append(f"| {r['group']} | {r['reports']} | {r['A']} | {r['P']} | {r['N']} | "
                     f"{pct(r['A_share'])} ({pct(r['A_low'])} to {pct(r['A_high'])}) |")
    lines += ["", "## By trigger", "", "| Trigger | Direct / stated |", "|---|---|"]
    for r in sorted(by_trigger, key=lambda r: -r["stated"]):
        lines.append(f"| {r['group']} {names.get(r['group'], '')} | {r['A']} / {r['stated']} |")
    lines += ["", "## By year of the incident", "", "| Year | Direct / stated |", "|---|---|"]
    for r in by_year:
        lines.append(f"| {r['group']} | {r['A']} / {r['stated']} |")
    lines += ["", "## How to reproduce", "", "```bash", "pip install git+https://github.com/yogeshramaswamy608/incident2chaos@v0.1.0", "incident2chaos coverage --by source",
              "```", "",
              "The corpus holds each report's link and labels, never its text. The labels of the reports outside the "
              "50-report pilot were proposed by a language model under the frozen codebook and checked by the author "
              "on a blind sample of 45 (injectability agreement 42 of 44, Cohen's kappa 0.91). Data: CC BY 4.0. Code: "
              "Apache 2.0.", ""]
    open(out, "w", encoding="utf-8").write("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1])
